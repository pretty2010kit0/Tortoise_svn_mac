pub mod svn;

/// 入口：窗口 + 命令注册（第一阶段 MVP 命令全集）
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .invoke_handler(tauri::generate_handler![
            svn::commands::svn_version,
            svn::commands::set_svn_executable,
            svn::history::history_add,
            svn::history::history_list,
            svn::favorites::fav_add,
            svn::favorites::fav_list,
            svn::favorites::fav_remove,
            svn::settings::get_external_diff,
            svn::settings::set_external_diff,
            svn::settings::cert_trust_list,
            svn::settings::cert_trust_add,
            svn::settings::cert_trust_remove,
            svn::fs_watch::wc_watch_start,
            svn::fs_watch::wc_watch_stop,
            svn::favorites::fav_clear,
            svn::commands::svn_auth_list,
            svn::commands::svn_auth_remove,
            svn::commands::remote_open,
            svn::commands::remote_open_auth,
            svn::commands::remote_open_trust,
            svn::commands::wc_ignore_add,
            svn::commands::remote_repo_layout,
            svn::commands::remote_list,
            svn::commands::remote_cat,
            svn::commands::remote_export,
            svn::commands::remote_mkdir,
            svn::commands::remote_delete,
            svn::commands::remote_copy,
            svn::commands::remote_move,
            svn::commands::remote_import,
            svn::commands::dir_stats,
            svn::commands::remote_proplist,
            svn::commands::remote_log,
            svn::commands::remote_diff,
            svn::commands::diff_chunks,
            svn::commands::wc_open,
            svn::commands::wc_status,
            svn::commands::wc_diff,
            svn::commands::wc_file_pair,
            svn::commands::wc_diff_external,
            svn::commands::wc_commit,
            svn::commands::wc_update,
            svn::commands::wc_checkout,
            svn::commands::wc_add,
            svn::commands::wc_delete,
            svn::commands::wc_resolve,
            svn::commands::wc_conflict_parse,
            svn::commands::wc_conflict_resolve,
            svn::commands::wc_cleanup,
            svn::commands::wc_upgrade,
            svn::commands::wc_revert,
            svn::commands::wc_proplist,
            svn::commands::wc_propset,
            svn::commands::wc_propdel,
            svn::commands::wc_lock,
            svn::commands::wc_unlock,
            svn::commands::wc_move,
            svn::commands::wc_set_log,
            svn::commands::wc_status_u,
            svn::commands::wc_blame,
            svn::commands::wc_changelist,
            svn::commands::wc_commit_cl,
            svn::commands::wc_switch,
            svn::commands::wc_relocate,
            svn::commands::wc_mergeinfo,
            svn::commands::wc_merge,
            svn::commands::wc_diff_text,
            svn::commands::wc_patch_apply,
            svn::commands::task_checkout,
            svn::commands::task_update,
            svn::commands::task_import,
            svn::commands::task_export,
            svn::commands::task_list,
            svn::commands::task_cancel,
            svn::commands::task_retry,
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
